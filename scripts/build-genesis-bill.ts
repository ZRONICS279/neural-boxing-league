/** Regenerates app/genesis-bill.ts — the display-safe genesis roster the site
 *  renders before the first poll lands.
 *
 *  The server-rendered ring page needs a plausible division listing on the
 *  very first paint, and the bundle must not carry the engine just to
 *  fabricate one. So the genesis league is computed HERE, once, run through
 *  the same `publicFighter` strip the roster route serves — careers and
 *  readable tendencies, no learned matrices — and written down as plain data.
 *
 *  Run it again whenever the genesis roster in `createInitialLeague` changes:
 *
 *    node --experimental-strip-types scripts/build-genesis-bill.ts
 */
import { writeFileSync } from "node:fs";
import { createInitialLeague } from "../app/simulation.ts";
import { publicLeague } from "../worker/league.ts";

const league = publicLeague(createInitialLeague());

const file = `// Generated by scripts/build-genesis-bill.ts — do not edit by hand.
// The genesis roster as the public knows it: careers and readable tendencies,
// no learned matrices. First-paint scaffolding only; the first poll replaces it.
import type { LeagueState } from "./fight-model.ts";

export const GENESIS_BILL: LeagueState = ${JSON.stringify(league)};
`;

writeFileSync(new URL("../app/genesis-bill.ts", import.meta.url), file);
console.log(
  `wrote app/genesis-bill.ts: ${league.roster.length} athletes, ${(file.length / 1024).toFixed(1)} KB`,
);
